import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { ServerState } from "./legacy-state-fixture.js";
import { gameResponse } from "../src/game-routes.js";
import { normalizeLocalGameState } from "../src/game.js";
import { FIXTURE_FUEL_AP, FIXTURE_FUEL_ID, fuelCycle, fuelStatus, supplyReference } from "../src/supply.js";

const directory = mkdtempSync(path.join(tmpdir(), "blustone-supply-"));
const filename = path.join(directory, "state.json");
const realNow = Date.now;
let now = Date.parse("2026-10-04T12:00:00Z");
try {
  Date.now = () => now;
  let state = new ServerState("http://localhost", filename);
  const guest = state.registerGuest({ device_id: "supply" }, {}).ret_data as { otp: string };
  const payload = { otp: guest.otp, id: FIXTURE_FUEL_ID };
  const account = state.accountFor(payload, {});
  let game = state.gameFor(account);
  game.ap = 40;
  const originalCards = JSON.stringify([game.starter_cards, game.recruited_cards, game.decks, game.card_book]);
  const call = (route: string, body = payload) => gameResponse(state, route, body, {}) as any;
  assert.throws(() => gameResponse(state, "/supply/ActivityReward", { id: FIXTURE_FUEL_ID }, {}), /authenticated account required/);
  const reference = call("/reference/V2_GetSupply").ret_data;
  assert.deepEqual(reference, supplyReference());
  assert.equal(reference.activity[0].id, FIXTURE_FUEL_ID);
  assert.ok([reference.attend, reference.attend_progress, reference.attend_newbie, reference.login_bonus].every(Array.isArray));
  const inventory = call("/lobby/V2_GetSupplyInst").ret_data;
  assert.deepEqual(inventory.activity, [{ id: FIXTURE_FUEL_ID, status: 1 }]);
  assert.equal(inventory.attend, undefined, "instance attendance must not receive reference array shape");
  assert.deepEqual(inventory.login_bonus, { cur_value: 1, cycle: 1, cycle_log: [] });
  assert.equal(inventory.activity_refresh_utc, Date.parse("2026-10-05T00:00:00Z") / 1000);
  const refresh = call("/supply/Refresh").ret_data;
  assert.equal(refresh.login_bonus, undefined);
  assert.deepEqual(refresh.activity, inventory.activity);
  assert.notEqual(call("/supply/ActivityReward", { ...payload, id: "AP1" }).result_code, 1, "AP resource id is not an activity id");
  assert.equal(game.ap, 40);
  const claimed = call("/supply/ActivityReward");
  assert.equal(claimed.result_code, 1);
  assert.deepEqual(claimed.ret_data.target_inst, { id: FIXTURE_FUEL_ID, status: 2 });
  assert.equal(claimed.ret_data.user.ap.cur, 40 + FIXTURE_FUEL_AP);
  assert.equal(typeof claimed.ret_data.user.ap.ap_charge_time, "number", "native reads deadline inside ap object");
  assert.equal(claimed.ret_data.user.ap_charge_time, undefined);
  assert.notEqual(call("/supply/ActivityReward").result_code, 1);
  assert.equal(game.ap, 40 + FIXTURE_FUEL_AP, "same-cycle duplicate does not grant again");
  state = new ServerState("http://localhost", filename);
  game = state.gameFor(state.accountFor(payload, {}));
  assert.equal(call("/lobby/V2_GetSupplyInst").ret_data.activity[0].status, 2);
  assert.notEqual(call("/supply/ActivityReward").result_code, 1, "claim persists through restart");
  assert.equal(JSON.stringify([game.starter_cards, game.recruited_cards, game.decks, game.card_book]), originalCards);
  const other = state.registerGuest({ device_id: "other-supply" }, {}).ret_data as { otp: string };
  assert.equal(call("/lobby/V2_GetSupplyInst", { otp: other.otp, id: FIXTURE_FUEL_ID }).ret_data.activity[0].status, 1, "account claims are isolated");
  now = Date.parse("2026-10-05T00:00:00Z");
  assert.equal(call("/supply/Refresh").ret_data.activity[0].status, 1);
  assert.equal(call("/supply/ActivityReward").ret_data.user.ap.cur, 60, "reward overflow is retained");
  now -= 86_400_000;
  assert.equal(call("/supply/Refresh").ret_data.activity[0].status, 2);
  assert.notEqual(call("/supply/ActivityReward").result_code, 1, "rollback must not reopen an already claimed cycle");
  assert.equal(normalizeLocalGameState({ ap: 33 }).supply_fuel_claim_day, -1, "legacy migration invents no prior claim");
  assert.throws(() => normalizeLocalGameState({ supply_fuel_claim_day: "bad" }), /Supply claim/);
  assert.equal(fuelStatus(-1, now), 1);
  assert.throws(() => fuelCycle(NaN), /Supply clock/);
  console.log("Supply: native bootstrap/reward shapes, daily fixture claims, isolation, rollback, overflow and restart passed; UI unverified.");
} finally {
  Date.now = realNow;
  rmSync(directory, { recursive: true, force: true });
}
