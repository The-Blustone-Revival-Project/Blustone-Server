import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { ServerState } from "./legacy-state-fixture.js";
import { BP_SHOP_ID, fuelItemReference, FUEL_SHOP_ID } from "../src/shop-fuel.js";
const directory = mkdtempSync(path.join(tmpdir(), "blustone-shop-fuel-"));
const filename = path.join(directory, "state.json");
const realNow = Date.now;
try {
  let now = Date.parse("2026-10-04T12:00:00Z"); Date.now = () => now;
  let state = new ServerState("http://localhost", filename);
  const auth = state.registerGuest({ device_id: "fuel-shop" }, {}).ret_data as { otp: string };
  let game = state.gameFor(state.accountFor(auth, {}));
  game.gacha_free_qty = 2; game.gacha_iap_qty = 20;
  const request = { ...auth, target_ref_id: FUEL_SHOP_ID, price_type: "1", item_inst_id: "0", qty: "1" };
  const reference = fuelItemReference();
  assert.equal(reference.item[0].use_type, 1);
  assert.equal(reference.item[0].effect, "10", "native atoi consumes a string effect");
  assert.deepEqual(reference.global_item[0].price_list.filter((row) => row.price_type === 1).map((row) => row.buy_cnt), [1, 2, 3]);
  const first = state.buyFuel(request, {}).ret_data as any;
  assert.deepEqual(first.user.iap, { iap_qty: 17, free_iap_qty: 0 }, "charge total5 once across pools");
  assert.equal(first.user.ap.cur, 60, "purchased overflow preserved");
  assert.equal(typeof first.user.ap.ap_charge_time, "number");
  assert.equal(first.user.ap_charge_time, undefined);
  assert.deepEqual(first.target_inst.buy_cnt, { prev: 0, cur: 1 });
  assert.equal(first.jackpot_level, 1); assert.equal(first.jackpot_multiply, 1);
  state = new ServerState("http://localhost", filename); game = state.gameFor(state.accountFor(auth, {}));
  const inventory = state.itemInventory(auth, {}).ret_data as any;
  assert.deepEqual(inventory.global_item[0], { item_id: FUEL_SHOP_ID, price_type: 1, buy_cnt: 1 });
  assert.equal(game.ap, 60);
  assert.equal(state.buyFuel(request, {}).result_code, 1);
  const goldBefore = game.gold;
  const gold = state.buyFuel({ ...request, price_type: "2" }, {}).ret_data as any;
  assert.deepEqual(gold.user.gold, { prev: goldBefore, cur: goldBefore - 100 });
  const beforeLimit = JSON.stringify(game);
  assert.notEqual(state.buyFuel(request, {}).result_code, 1);
  assert.notEqual(state.buyFuel({ ...request, price_type: "2" }, {}).result_code, 1, "native capacity is shared across currencies");
  assert.equal(JSON.stringify(game), beforeLimit);
  for (const invalid of [{ qty: 2 }, { qty: true }, { price_type: 4 }, { item_inst_id: 1 }, { target_ref_id: "AP1" }]) {
    const before = JSON.stringify(game);
    assert.notEqual(state.buyFuel({ ...request, ...invalid }, {}).result_code, 1);
    assert.equal(JSON.stringify(game), before);
  }
  now -= 86_400_000;
  assert.notEqual(state.buyFuel(request, {}).result_code, 1, "rollback must not reopen capped cycle");
  now += 2 * 86_400_000;
  assert.equal(state.buyFuel(request, {}).result_code, 1, "new UTCday resets local counter");
  const other = state.registerGuest({ device_id: "other-fuel-shop" }, {}).ret_data as { otp: string };
  assert.equal((state.itemInventory(other, {}).ret_data as any).global_item[0].buy_cnt, 0);
  game.gacha_iap_qty = 0; game.gacha_free_qty = 0;
  const insufficient = JSON.stringify(game);
  assert.notEqual(state.buyFuel(request, {}).result_code, 1);
  assert.equal(JSON.stringify(game), insufficient);
  const bpReference = reference.item.find((row) => row.id === BP_SHOP_ID)!;
  assert.equal(bpReference.use_type, 2);
  assert.equal(bpReference.effect, "5");
  const apBeforeBp = game.ap, bpBefore = game.bp, goldBeforeBp = game.gold;
  const bpRequest = { ...request, target_ref_id: BP_SHOP_ID, price_type: "2" };
  const bpResult = state.buyFuel(bpRequest, {}).ret_data as any;
  assert.deepEqual(bpResult.user.bp, { prev: bpBefore, cur: bpBefore + 5, bp_charge_time: now / 1000 + 1800 });
  assert.equal(bpResult.user.ap, undefined, "BP receipt must not update AP");
  assert.equal(game.ap, apBeforeBp);
  assert.equal(game.gold, goldBeforeBp - 100);
  assert.equal(game.bp_shop.gold, 1);
  assert.equal(game.fuel_shop.gold, 0, "resource counters stay independent");
  const bpRestart = new ServerState("http://localhost", filename);
  const bpGame = bpRestart.gameFor(bpRestart.accountFor(auth, {}));
  assert.equal(bpGame.bp, bpBefore + 5);
  const bpInventory = (bpRestart.itemInventory(auth, {}).ret_data as any).global_item;
  assert.equal(bpInventory.find((row: any) => row.item_id === BP_SHOP_ID && row.price_type === 2).buy_cnt, 1);
  assert.equal(bpRestart.buyFuel(bpRequest, {}).result_code, 1);
  assert.equal(bpRestart.buyFuel(bpRequest, {}).result_code, 1);
  assert.notEqual(bpRestart.buyFuel(bpRequest, {}).result_code, 1);
  now += 86_400_000;
  bpGame.gacha_free_qty = 5;
  bpGame.gacha_iap_qty = 0;
  const bpManda = bpRestart.buyFuel({ ...bpRequest, price_type: 1 }, {}).ret_data as any;
  assert.deepEqual(bpManda.user.iap, { iap_qty: 0, free_iap_qty: 0 });
  assert.equal(bpGame.bp_shop.manda, 1);
  assert.equal(bpGame.bp_shop.gold, 0, "new UTC day resets both BP payment counters");
  assert.equal(bpRestart.buyFuel(bpRequest, {}).result_code, 1);
  assert.equal(bpRestart.buyFuel(bpRequest, {}).result_code, 1);
  const bpCapped = JSON.stringify(bpGame);
  assert.notEqual(bpRestart.buyFuel({ ...bpRequest, price_type: 1 }, {}).result_code, 1);
  assert.equal(JSON.stringify(bpGame), bpCapped, "mixed BP capacity refuses atomically");
  assert.equal((bpRestart.itemInventory(other, {}).ret_data as any).global_item.find((row: any) => row.item_id === BP_SHOP_ID).buy_cnt, 0);
  console.log("ShopFuel: AP/BP references, receipts, resource isolation, shared currency capacity, daily reset, rollback, refusal and restart passed; native UI unverified.");
} finally { Date.now = realNow; rmSync(directory, { recursive: true, force: true }); }
