import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { ServerState } from "./legacy-state-fixture.js";
import { gameResponse } from "../src/game-routes.js";
import { campaignReceiptProjection, recordCampaignReceipt } from "../src/campaign-receipt-trace.js";
const directory = mkdtempSync(path.join(tmpdir(), "blustone-receipts-"));
const cwd = process.cwd(), previous = process.env.BLUSTONE_CAMPAIGN_RECEIPT_TRACE;
try {
  process.chdir(directory);
  const state = new ServerState("http://localhost", path.join(directory, "state.json"));
  const auth = state.registerGuest({ device_id: "receipt-test" }, {}).ret_data as { otp: string };
  const game = state.gameFor(state.accountFor(auth, {}));
  const saved = readFileSync(path.join(directory, "state.json"), "utf8");
  const snapshot = JSON.stringify(game);
  state.campaignTraceContext(auth, {"x-pv-accesstoken":"UNBOUND_TRACE_TEST"});
  assert.equal(JSON.stringify(game), snapshot);
  assert.equal(readFileSync(path.join(directory, "state.json"), "utf8"), saved);
  assert.equal((state as any).sessionPvidByAccessToken.has("UNBOUND_TRACE_TEST"), false);
  const payload = { ...auth, stage_id: "n_01_01", deck_inst_id_1: 1, secret: "SECRET_BAIT" };
  delete process.env.BLUSTONE_CAMPAIGN_RECEIPT_TRACE;
  gameResponse(state, "/mission/Start", payload);
  const context = state.campaignTraceContext(auth, {});
  context.reservation!.deck_inst_ids.length = 0;
  assert.ok(game.active_battle!.deck_inst_ids.length > 0);
  process.env.BLUSTONE_CAMPAIGN_RECEIPT_TRACE = "1";
  const complete = { ...payload, play_info: JSON.stringify({ clear: 1, clear_time: 10, dead_cnt: 0, token: "SECRET_BAIT" }) };
  const reply = gameResponse(state, "/mission/Complete", complete) as any;
  const row = JSON.parse(readFileSync(path.join(directory, "logs/campaign-receipts.ndjson"), "utf8"));
  assert.equal(row.reservation_before.state, "active");
  assert.equal(row.wallet.exp.cur - row.wallet.exp.prev, 30);
  assert.deepEqual(row.cards, reply.ret_data.card);
  assert.ok(!JSON.stringify(row).includes("SECRET_BAIT"));
  assert.ok(!JSON.stringify(row).includes(auth.otp));
  const gold = game.gold;
  assert.equal((gameResponse(state, "/mission/Complete", complete) as any).ret_data.accepted, false);
  assert.equal(game.gold, gold);
  const original = state.campaignTraceContext;
  state.campaignTraceContext = () => { throw Error("diagnostic failure"); };
  assert.equal((gameResponse(state, "/mission/Complete", complete) as any).ret_data.accepted, false);
  let reads = 0;
  state.campaignTraceContext = function(p, h) { if (++reads === 2) throw Error("post-settlement failure"); return original.call(this, p, h); };
  assert.equal((gameResponse(state, "/mission/Start", { ...payload, stage_id: "n_01_02" }) as any).result_code, 1);
  state.campaignTraceContext = original;
  const clean = state.campaignTraceContext(auth, {});
  const poisoned = {...clean, reservation: {battle_id:"SECRET_BAIT",stage_id:"SECRET_BAIT",state:"SECRET_BAIT",deck_inst_ids:[1]}};
  const projected = campaignReceiptProjection("/mission/ReqAchieveReward", { area_id: "n_01", target_achieve_cnt: "20", play_info: "invalid SECRET_BAIT" }, { result_code: 1, ret_data: { achieve_cnt:20,claimed:true,gold:{prev:1,cur:21}, card: { "1": { prev: 0, cur: 10, otp: "SECRET_BAIT" }, SECRET_BAIT: {} }, token: "SECRET_BAIT" } }, poisoned, clean)!;
  assert.ok(!JSON.stringify(projected).includes("SECRET_BAIT"));
  assert.equal(projected.requested_achieve_cnt, 20);
  assert.equal(projected.returned_claimed, true);
  assert.deepEqual(projected.wallet.gold, {prev:1,cur:21});
  assert.equal(campaignReceiptProjection("/mission/Start", {stage_id: "SECRET_BAIT"}, {}, clean, clean), undefined);
  recordCampaignReceipt(projected, () => { throw Error("SECRET_BAIT"); });
  rmSync(path.join(directory, "logs/campaign-receipts.ndjson"));
  mkdirSync(path.join(directory, "logs/campaign-receipts.ndjson"));
  assert.equal((gameResponse(state, "/mission/Complete", { ...complete, stage_id: "n_01_02" }) as any).ret_data.accepted, true);
  console.log("Campaign receipt trace: privacy, EXP correlation, immutable reads, duplicate isolation and fail-open diagnostics passed.");
} finally {
  process.chdir(cwd);
  if (previous === undefined) delete process.env.BLUSTONE_CAMPAIGN_RECEIPT_TRACE;
  else process.env.BLUSTONE_CAMPAIGN_RECEIPT_TRACE = previous;
  rmSync(directory, { recursive: true, force: true });
}
