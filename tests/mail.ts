import assert from "node:assert/strict";
import { mkdtempSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { ServerState } from "./legacy-state-fixture.js";
import { gameResponse } from "../src/game-routes.js";
import { LOCAL_MAIL_SENDER, mailboxRequest, normalizeMail } from "../src/mail.js";

const dir = mkdtempSync(path.join(os.tmpdir(), "blustone-mail-"));
const file = path.join(dir, "state.json");
try {
  let state = new ServerState("http://localhost", file);
  const auth = state.registerGuest({ device_id: "mail" }, {}).ret_data as { otp: string };
  let game = state.gameFor(state.accountFor(auth, {}));
  const req = (route: string, fields: Record<string, unknown> = {}) => gameResponse(state, `/message/${route}`, { ...auth, ...fields }) as any;
  const page = { start: "0", length: "20", after: "0", before: "0" };
  const initial = JSON.stringify(game);
  assert.deepEqual(req("GetReceivedList", page).ret_data, { unread_count: 0, list: [] });
  assert.deepEqual(req("GetUnreadCount").ret_data, { unread_count: 0 });
  assert.equal(JSON.stringify(game), initial, "empty mailbox reads do not fabricate rewards or visits");
  assert.notEqual(req("Read", { target_list: "1" }).result_code, 1);
  assert.equal(state.startMission({ ...auth, stage_id: "n_01_01" }, {}).result_code, 1);
  state.completeMission({ ...auth, stage_id: "n_01_01", play_info: '{"clear":0}' }, {});
  assert.equal(game.mail.received.length, 0, "defeat creates no victory notice");
  state.startMission({ ...auth, stage_id: "n_01_01" }, {});
  state.completeMission({ ...auth, stage_id: "n_01_01", play_info: '{"clear":1}' }, {});
  const rows = req("GetReceivedList", page).ret_data;
  assert.equal(rows.list[0].sender_pvid, LOCAL_MAIL_SENDER.pvid, "nonzero sender avoids native recipient fallback");
  assert.equal(rows.list[0].sender_nickname, LOCAL_MAIL_SENDER.nickname);
  assert.equal(rows.list[0].receiver_pvid, state.accountFor(auth, {}).pvid);
  const beforeProfile = JSON.stringify(game);
  const senderProfile = gameResponse(state, "/relation/GetTargetUserInfo", { ...auth, list: "[1]" }) as any;
  assert.equal(senderProfile.ret_data.list.length, 1);
  assert.equal(senderProfile.ret_data.list[0].pvid, LOCAL_MAIL_SENDER.pvid);
  assert.equal(senderProfile.ret_data.list[0].nick_name, LOCAL_MAIL_SENDER.nickname);
  assert.equal(senderProfile.ret_data.list[0].profile_url, "http://localhost/local-profile/replica-100.png");
  assert.equal(typeof senderProfile.ret_data.list[0].profile_status, "string");
  const senderDetail = gameResponse(state, "/world/GetUserDetail", { ...auth, list: "[1]" }) as any;
  assert.ok(Array.isArray(senderDetail.ret_data), "second-stage profile callback requires bare detail rows");
  assert.equal(senderDetail.ret_data.length, 1);
  assert.equal(senderDetail.ret_data[0].pvid, LOCAL_MAIL_SENDER.pvid);
  assert.equal(senderDetail.ret_data[0].ref_id_leader, "001");
  assert.notEqual((gameResponse(state, "/world/GetUserDetail", { ...auth, list: "[999]" }) as any).result_code, 1);
  assert.throws(() => gameResponse(state, "/world/GetUserDetail", { list: "[1]" }), /authenticated account required/);
  assert.equal(JSON.stringify(game), beforeProfile, "display lookup creates no account-owned game state or reward");
  assert.throws(() => gameResponse(state, "/relation/GetTargetUserInfo", { list: "[1]" }), /authenticated account required/);
  assert.equal(rows.unread_count, 1); assert.equal(rows.list.length, 1);
  const row = rows.list[0];
  assert.equal(row.receiver_pvid, state.accountFor(auth, {}).pvid);
  assert.equal(row.from_admin, 1); assert.equal(row.attachment, null);
  assert.equal(typeof row.content, "string"); assert.ok(row.content.includes("no attachment"));
  assert.equal(typeof row.created_datetime, "number");
  const balances = [game.gold, game.exp, game.ap, game.bp, game.gacha_free_qty, game.gacha_iap_qty];
  const ownership = JSON.stringify([game.items, game.starter_cards, game.recruited_cards, game.stage_achievements, game.tutorial]);
  for (const bad of [{ target_list: [row.id] }, { target_list: "1,2" }, { target_list: "999" }, { target_list: "" }]) {
    const before = JSON.stringify(game); assert.notEqual(req("Read", bad).result_code, 1); assert.equal(JSON.stringify(game), before);
  }
  assert.notEqual(req("GetReceivedList", { ...page, length: 101 }).result_code, 1);
  assert.notEqual(req("GetReceivedList", { ...page, start: -1 }).result_code, 1);
  const other = state.registerGuest({ device_id: "other-mail" }, {}).ret_data as { otp: string };
  assert.notEqual(gameResponse(state, "/message/Read", { ...other, target_list: String(row.id) }).result_code, 1);
  assert.equal(req("TakeAttachment", { target_list: String(row.id) }).result_code === 1, false, "no false attachment success");
  assert.notEqual(req("Send", { receiver_pvid: 1, content: "unused" }).result_code, 1, "outbound transport remains disabled");
  assert.deepEqual(req("Read", { target_list: String(row.id) }).ret_data, { unread_count: 0, target_list: [row.id] });
  const readState = JSON.stringify(game);
  req("Read", { target_list: String(row.id) }); assert.equal(JSON.stringify(game), readState);
  state = new ServerState("http://localhost", file); game = state.gameFor(state.accountFor(auth, {}));
  assert.equal(req("GetReceivedList", page).ret_data.list[0].is_read, 1);
  assert.deepEqual(req("Archive", { target_list: String(row.id) }).ret_data, { unread_count: 0, target_list: [row.id] });
  assert.deepEqual(req("GetReceivedList", page).ret_data.list, []);
  const archiveState = JSON.stringify(game); req("Archive", { target_list: String(row.id) }); assert.equal(JSON.stringify(game), archiveState);
  assert.deepEqual([game.gold, game.exp, game.ap, game.bp, game.gacha_free_qty, game.gacha_iap_qty], balances);
  assert.equal(JSON.stringify([game.items, game.starter_cards, game.recruited_cards, game.stage_achievements, game.tutorial]), ownership);
  state.startMission({ ...auth, stage_id: "n_01_02" }, {});
  state.completeMission({ ...auth, stage_id: "n_01_02", play_info: '{"clear":1}' }, {});
  assert.equal(game.mail.received.length, 1, "one observed-victory notice, not every battle or an archive-triggered regrant");
  state = new ServerState("http://localhost", file); game = state.gameFor(state.accountFor(auth, {}));
  assert.equal(game.mail.received[0].is_archived, 1);
  for (const target_list of ["", "0,", "1,,", "1,999,", "9007199254740992,", [row.id]]) {
    const before = JSON.stringify(game);
    assert.notEqual(req("RemoveReceived", { target_list }).result_code, 1);
    assert.equal(JSON.stringify(game), before, "invalid batch cannot partially delete");
  }
  assert.notEqual(gameResponse(state, "/message/RemoveReceived", { ...other, target_list: `${row.id},` }).result_code, 1);
  const beforeDelete = JSON.stringify({ ...game, mail: null });
  assert.deepEqual(req("RemoveReceived", { target_list: `${row.id},` }).ret_data, { unread_count: 0, target_list: [row.id] });
  assert.equal(game.mail.received.length, 0);
  assert.deepEqual(game.mail.deleted, [row.id]);
  assert.equal(JSON.stringify({ ...game, mail: null }), beforeDelete, "deletion has no gameplay effects");
  const deletedState = JSON.stringify(game);
  assert.deepEqual(req("RemoveReceived", { target_list: `${row.id},${row.id},` }).ret_data.target_list, [row.id]);
  assert.equal(JSON.stringify(game), deletedState);
  state = new ServerState("http://localhost", file); game = state.gameFor(state.accountFor(auth, {}));
  assert.deepEqual(req("RemoveReceived", { target_list: `${row.id},` }).ret_data, { unread_count: 0, target_list: [row.id] });
  assert.equal(game.mail.victory_notice_sent, true);
  assert.equal(game.mail.received.length, 0);
  assert.notEqual(req("RemoveSent", { target_list: `${row.id},` }).result_code, 1);
  assert.deepEqual(normalizeMail({ next_id: 1, victory_notice_sent: false, received: [] }).deleted, [], "legacy mailbox migration");
  assert.throws(() => normalizeMail({ ...game.mail, deleted: [row.id, row.id] }), /Malformed/);
  const batch = normalizeMail({ next_id: 3, victory_notice_sent: true, received: [1, 2].map((id) => ({
    id, content: "Disposable deletion fixture", created_datetime: 1, is_read: 0, is_archived: 0 })) });
  let writes = 0;
  const remove = (target_list: string) => mailboxRequest("/message/RemoveReceived", { target_list }, batch, 1, "Fixture", () => writes++);
  const batchBefore = JSON.stringify(batch);
  assert.ok("error" in remove("1,99,"));
  assert.equal(JSON.stringify(batch), batchBefore); assert.equal(writes, 0);
  assert.deepEqual(remove("1,2,"), { data: { unread_count: 0, target_list: [1, 2] } });
  assert.equal(writes, 1); assert.equal(batch.received.length, 0);
  assert.deepEqual(remove("2,1,"), { data: { unread_count: 0, target_list: [2, 1] } });
  assert.equal(writes, 1);
  assert.deepEqual(req("GetSentList", page).ret_data, { unread_count: 0, list: [] });
  assert.throws(() => normalizeMail({ next_id: 1, victory_notice_sent: false, received: [{ id: 1 }] }), /Malformed/);
  console.log("Mail: earned notice, native receipts, read/archive/delete restart/replay, atomic deletion validation and account isolation passed; native UI pending.");
} finally { rmSync(dir, { recursive: true, force: true }); }
